-- Convert curriculum entity identifiers and every relational reference to BIGINT.
-- USER_PROGRESS.item_id remains polymorphic, so the service validates its target.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'lessons'
      AND column_name = 'id' AND data_type = 'character varying'
  ) THEN
    ALTER TABLE lessons ADD COLUMN id_numeric BIGINT GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE exercises ADD COLUMN id_numeric BIGINT GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE exercises ADD COLUMN lesson_id_numeric BIGINT;
    ALTER TABLE ai_chats ADD COLUMN exercise_id_numeric BIGINT;
    ALTER TABLE user_progress ADD COLUMN item_id_numeric BIGINT;

    UPDATE exercises AS exercise
      SET lesson_id_numeric = lesson.id_numeric
      FROM lessons AS lesson
      WHERE lesson.id = exercise.lesson_id;

    UPDATE ai_chats AS chat
      SET exercise_id_numeric = exercise.id_numeric
      FROM exercises AS exercise
      WHERE exercise.id = chat.exercise_id;

    UPDATE user_progress AS progress
      SET item_id_numeric = CASE
        WHEN progress.item_type = 'lesson' THEN (
          SELECT lesson.id_numeric FROM lessons AS lesson WHERE lesson.id = progress.item_id
        )
        WHEN progress.item_type = 'exercise' THEN (
          SELECT exercise.id_numeric FROM exercises AS exercise WHERE exercise.id = progress.item_id
        )
      END;

    IF EXISTS (SELECT 1 FROM exercises WHERE lesson_id_numeric IS NULL)
       OR EXISTS (SELECT 1 FROM ai_chats WHERE exercise_id IS NOT NULL AND exercise_id_numeric IS NULL)
       OR EXISTS (SELECT 1 FROM user_progress WHERE item_id_numeric IS NULL) THEN
      RAISE EXCEPTION 'Cannot migrate curriculum IDs: one or more stored references do not resolve';
    END IF;

    ALTER TABLE exercises DROP CONSTRAINT IF EXISTS exercises_lesson_id_fkey;
    ALTER TABLE ai_chats DROP CONSTRAINT IF EXISTS ai_chats_exercise_id_fkey;
    ALTER TABLE user_progress DROP CONSTRAINT IF EXISTS user_progress_user_id_item_type_item_id_key;
    ALTER TABLE lessons DROP CONSTRAINT IF EXISTS lessons_pkey;
    ALTER TABLE exercises DROP CONSTRAINT IF EXISTS exercises_pkey;
    DROP INDEX IF EXISTS exercises_lesson_idx;
    DROP INDEX IF EXISTS ai_chats_exercise_idx;

    ALTER TABLE lessons DROP COLUMN id;
    ALTER TABLE lessons RENAME COLUMN id_numeric TO id;
    ALTER TABLE lessons ADD CONSTRAINT lessons_pkey PRIMARY KEY (id);

    ALTER TABLE exercises DROP COLUMN lesson_id;
    ALTER TABLE exercises RENAME COLUMN lesson_id_numeric TO lesson_id;
    ALTER TABLE exercises ALTER COLUMN lesson_id SET NOT NULL;
    ALTER TABLE exercises DROP COLUMN id;
    ALTER TABLE exercises RENAME COLUMN id_numeric TO id;
    ALTER TABLE exercises ADD CONSTRAINT exercises_pkey PRIMARY KEY (id);
    ALTER TABLE exercises ADD CONSTRAINT exercises_lesson_id_fkey
      FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE;

    ALTER TABLE ai_chats DROP COLUMN exercise_id;
    ALTER TABLE ai_chats RENAME COLUMN exercise_id_numeric TO exercise_id;
    ALTER TABLE ai_chats ADD CONSTRAINT ai_chats_exercise_id_fkey
      FOREIGN KEY (exercise_id) REFERENCES exercises(id) ON DELETE SET NULL;

    ALTER TABLE user_progress DROP COLUMN item_id;
    ALTER TABLE user_progress RENAME COLUMN item_id_numeric TO item_id;
    ALTER TABLE user_progress ALTER COLUMN item_id SET NOT NULL;
    ALTER TABLE user_progress ADD CONSTRAINT user_progress_user_id_item_type_item_id_key
      UNIQUE (user_id, item_type, item_id);

    CREATE INDEX exercises_lesson_idx ON exercises(lesson_id);
    CREATE INDEX ai_chats_exercise_idx ON ai_chats(exercise_id);
  END IF;
END $$;
