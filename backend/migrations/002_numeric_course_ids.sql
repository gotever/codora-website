-- Preserve the human-readable course key while making relational course IDs numeric.
-- This migration keeps the existing six tables and backfills every lesson FK.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'courses'
      AND column_name = 'id' AND data_type = 'character varying'
  ) THEN
    ALTER TABLE lessons DROP CONSTRAINT IF EXISTS lessons_course_id_fkey;
    ALTER TABLE courses RENAME COLUMN id TO slug;
    ALTER TABLE courses DROP CONSTRAINT IF EXISTS courses_pkey;
    ALTER TABLE courses ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
    ALTER TABLE courses ADD CONSTRAINT courses_pkey PRIMARY KEY (id);
    ALTER TABLE courses ADD CONSTRAINT courses_slug_key UNIQUE (slug);
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'lessons'
      AND column_name = 'course_id' AND data_type = 'character varying'
  ) THEN
    ALTER TABLE lessons ADD COLUMN course_id_numeric BIGINT;
    UPDATE lessons AS lesson
      SET course_id_numeric = course.id
      FROM courses AS course
      WHERE course.slug = lesson.course_id;

    IF EXISTS (SELECT 1 FROM lessons WHERE course_id_numeric IS NULL) THEN
      RAISE EXCEPTION 'Cannot migrate lessons: one or more course_id values do not match courses.slug';
    END IF;

    ALTER TABLE lessons ALTER COLUMN course_id_numeric SET NOT NULL;
    DROP INDEX IF EXISTS lessons_course_order_idx;
    ALTER TABLE lessons DROP CONSTRAINT IF EXISTS lessons_course_id_fkey;
    ALTER TABLE lessons DROP CONSTRAINT IF EXISTS lessons_course_id_order_index_key;
    ALTER TABLE lessons DROP COLUMN course_id;
    ALTER TABLE lessons RENAME COLUMN course_id_numeric TO course_id;
    ALTER TABLE lessons ADD CONSTRAINT lessons_course_id_fkey
      FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE;
    ALTER TABLE lessons ADD CONSTRAINT lessons_course_id_order_index_key
      UNIQUE (course_id, order_index);
    CREATE INDEX lessons_course_order_idx ON lessons(course_id, order_index);
  END IF;
END $$;
